-- Proposta técnica para PostgreSQL gerenciado (Supabase) / PostGIS.
-- NÃO executada. Não contém dados reais. Aplicar e validar em instância provisionada.
create extension if not exists postgis;
create schema if not exists private;

create table if not exists public.grupo_economico (
 id bigint generated by default as identity primary key,
 nome text not null unique,
 atualizado_em timestamptz not null default now()
);

create table if not exists public.distribuidora (
 dist integer primary key,
 sigla text not null,
 nome text not null,
 ativa boolean not null default true
);

create table if not exists public.distribuidora_grupo (
 dist integer not null references public.distribuidora(dist),
 grupo_id bigint not null references public.grupo_economico(id),
 validade_inicio date not null,
 validade_fim date,
 primary key(dist, validade_inicio),
 check (validade_fim is null or validade_fim >= validade_inicio)
);

create table if not exists public.snapshot_bdgd (
 id bigint generated by default as identity primary key,
 dist integer not null references public.distribuidora(dist),
 data_base date not null,
 origem_url text not null,
 sha256 text not null,
 data_processamento timestamptz not null default now(),
 dda_versao text not null,
 published boolean not null default false,
 unique (dist, data_base, sha256)
);

create unique index if not exists snapshot_um_publicado_por_dist
 on public.snapshot_bdgd(dist) where published;

create table if not exists public.entidade (
 codigo text primary key,
 nome text not null,
 familia text not null,
 unidade text not null check (unidade in ('un.','km','kVA','MVA','MWh')),
 metrica_padrao text not null,
 ativo boolean not null default true
);

create table if not exists public.dda_dominio (
 id bigint generated by default as identity primary key,
 versao text not null,
 entidade text not null references public.entidade(codigo),
 atributo text not null,
 codigo_interno text not null,
 descricao text not null,
 unique (versao, entidade, atributo, codigo_interno)
);

-- Granularidade: snapshot × entidade × combinação válida de dimensões.
-- dimensoes contém códigos internos de domínio, traduzidos para descrições
-- pela API/consulta de dim_dominio. API publica nomes descritivos.
create table if not exists public.ativo_agregado (
 snapshot_id bigint not null references public.snapshot_bdgd(id),
 entidade text not null references public.entidade(codigo),
 dimensoes jsonb not null default '{}'::jsonb,
 dimensoes_hash text not null,
 quantidade bigint,
 extensao_km numeric(20,5),
 potencia_kva numeric(22,5),
 outros_indicadores jsonb,
 primary key(snapshot_id, entidade, dimensoes_hash),
 check (quantidade is null or quantidade >= 0),
 check (extensao_km is null or extensao_km >= 0),
 check (potencia_kva is null or potencia_kva >= 0)
);
create index if not exists ativo_agregado_snapshot_entidade_idx on public.ativo_agregado(snapshot_id, entidade);
create index if not exists ativo_agregado_dimensoes_gin_idx on public.ativo_agregado using gin(dimensoes jsonb_path_ops);

-- Publicar geometrias poligonais simplificadas separadas em partes.
-- Geometria bruta deve permanecer no processamento privado, nunca nesta tabela.
create table if not exists public.arat_simplificada (
 snapshot_id bigint not null references public.snapshot_bdgd(id),
 parte integer not null,
 dist integer not null references public.distribuidora(dist),
 geom geometry(MultiPolygon, 4674) not null,
 checksum_origem text not null,
 primary key(snapshot_id,parte)
);
create index if not exists arat_simplificada_geom_gist on public.arat_simplificada using gist(geom);

-- Projeto público sem login: conceder SELECT somente a tabelas agregadas
-- que contenham EXCLUSIVAMENTE informação aprovada para divulgação.
-- Regras de RLS são defesa em profundidade, além dos GRANTs mínimos.
alter table public.grupo_economico enable row level security;
alter table public.distribuidora enable row level security;
alter table public.distribuidora_grupo enable row level security;
alter table public.snapshot_bdgd enable row level security;
alter table public.entidade enable row level security;
alter table public.dda_dominio enable row level security;
alter table public.ativo_agregado enable row level security;
alter table public.arat_simplificada enable row level security;

-- Não habilitar anon direto sobre fatos/ARAT antes de aprovar licenciamento,
-- critérios de qualidade e publicação de cada coluna. Preferir API server-side
-- read-only com usuário de banco próprio e privilégios restritos.
revoke all on all tables in schema public from anon, authenticated;
